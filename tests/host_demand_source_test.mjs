import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const main=read('firmware/esp8266/esp8266.ino');
const panel=read('firmware/esp8266/src/SemanticPanelService.h');
const serial=read('firmware/esp8266/src/HostSerial.h');
const build=read('tools/build-firmware.ps1');
assert(!panel.includes('hostLink.framesReceived()!=0'),'historical traffic is not a current subscription');
assert(panel.includes('hostDemand.wants(BoardCore::Protocol::UsbDemand::Panel,now)'));
assert(panel.includes('if(webSocket.count())webSocket.textAll(panelEventJson(event))'));
assert(main.includes('if(hostDemand.wants(UsbDemand::Status,millis())&&hostSerial.availableForWrite()>=kMaximumEncoded)sendHostStatus(0)'));
assert(main.includes('if(hostDemand.wants(UsbDemand::Peripheral,millis())'));
assert(main.includes('hostDemand.clear();usbTableCapture.clear();hostCallerAdmitted=false'));
const disconnected=main.slice(main.indexOf('  if(!PakarHost::connected()) {'),main.indexOf('  hostDemand.remaining(millis());'));
assert(disconnected.includes('hostFrameIngress.discard()'));
assert(disconnected.includes('hostLink.discardInput();hostLink.begin(115200,onHostFrameIngress)'));
assert(disconnected.indexOf('hostLink.discardInput()')<disconnected.indexOf('hostLink.begin('));
assert(!disconnected.includes('PakarHost::begin()'),'Reconnect retires framing without restarting USB hardware');
const snapshot=main.slice(main.indexOf('String buildUsbTableSnapshot(bool includePixels) {'),main.indexOf('void configureNtp()'));
assert(snapshot.includes('if(includePixels)body+=grid.pixelFrameJson();else body+=F("null")'));
assert(main.includes('(capturedPixels&&!hostDemand.wants(UsbDemand::Pixels,millis()))'));
assert(main.includes('offset+count==total)'),'last chunk retires the retained capture');
assert(main.includes('inner==kPixelDiagnostic'));
assert(main.includes('if(command.payloadLength!=7 || p[6]>1 || !applyPixelDiagnostic'));
assert(main.includes('!applyPixelDiagnostic(index.as<uint16_t>()'));
assert(main.includes('hostLink.ack(frame.sequence,kPixelDiagnostic)'));
const helper=main.slice(main.indexOf('bool applyPixelDiagnostic('),main.indexOf('void sendHostStatus('));
for(const fence of ['programmingLatched','otaActive','otaRebootAt','urbootBusy.get()','avrUploadOwner','remoteFirmware.busy()','networkApplyPending','cloudApplyPending'])
  assert(helper.includes(fence),fence);
assert(helper.includes('grid.diagnostic(index,count,rgb,off)')&&!helper.includes('mode ='));
assert(serial.indexOf('serial.enableReboot(false)')<serial.indexOf('serial.begin(115200)'));
assert(serial.indexOf('serial.enableReboot(false)')<serial.indexOf('USB.begin()'));
assert(serial.indexOf('USB.productName("PakarController")')<serial.indexOf('serial.begin(115200)'));
assert(serial.indexOf('USB.productName("PakarController")')<serial.indexOf('USB.begin()'));
assert(serial.includes('return tud_cdc_n_connected(0)'));
assert(serial.includes('inline bool connected(){return true;}'),'UART0 cannot truthfully observe bridge DTR');
assert(build.includes("[ValidateSet('uart0','hwcdc','otg')] [string] $S3HostTransport = 'uart0'"));
assert(build.includes("$cdcBoot=if($S3HostTransport -eq 'otg'){'default'}else{'cdc'}"));
assert(build.includes("$usbMode=if($S3HostTransport -eq 'otg'){'default'}else{'hwcdc'}"));
assert(build.includes("if($board -eq 'esp32s3' -and $S3HostTransport -ne 'uart0')"));
assert(build.includes('$output=Join-Path $build ("esp32s3-buffered-$S3HostTransport")'));
assert(build.includes('Join-Path $build "cache/$board$suffix"'),'Variants must reuse the same existing compiler cache');
assert(!build.includes('cache/$board$suffix-$S3HostTransport'));
assert(!build.includes('-DARDUINO_USB_CDC_ON_BOOT=1 -DARDUINO_USB_MODE=1'));
console.log('USB demand integration, pre-serialization gating, boot-fenced pixel diagnostic and explicit SDK CDC initialization source guards passed.');
