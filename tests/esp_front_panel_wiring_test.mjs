assert.match(runtime,/p\[0\] != espPendingAction_/);
assert.match(runtime,/uint8_t response\[40\] = \{1, 6, 0xFF, 0\}/);
assert.match(runtime,/case PC::HostMenuDirectory: case PC::HostMenuContent: case PC::HostMenuStateGet:\s+return P::kUnsupported/);
