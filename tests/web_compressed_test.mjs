import assert from 'node:assert/strict';
import {readFile,stat} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {compressedWebHeader,generateWebCompressed,webUiPayload} from '../tools/generate-web-compressed.mjs';
const read=path=>readFile(new URL('../'+path,import.meta.url),'utf8');
const source=await read('firmware/esp/src/WebUi.h'),asset='firmware/esp/src/WebUiCompressed.h';
const expected=compressedWebHeader(source),header=await read(asset);
assert.equal(header,expected.header);
const packed=Buffer.from(header.match(/PROGMEM = \{([\s\S]*?)\};/)[1].trim().split(',').map(x=>x.trim()).filter(Boolean).map(Number));
assert.deepEqual(gunzipSync(packed),webUiPayload(source),'Every canonical UI byte retained');
assert.deepEqual(compressedWebHeader(source.replaceAll('\r\n','\n').replaceAll('\n','\r\n')).gzip,packed,'Portable CRLF/LF source');
assert.equal(packed.readUInt32LE(4),0);assert.equal(packed[9],255);
assert(packed.length<expected.raw.length/2,'Keep meaningful ESP8266 flash headroom');
assert.notEqual(compressedWebHeader(source.replace('R"HTML(','R"HTML(<!-- fixture change -->')).header,header,'Changed UI cannot reuse stale gzip');
assert.throws(()=>webUiPayload('missing raw literal'));
assert.throws(()=>webUiPayload(source+'R"HTML('));
const before=await stat(new URL('../'+asset,import.meta.url));
await generateWebCompressed({check:true});
assert.equal((await stat(new URL('../'+asset,import.meta.url))).mtimeMs,before.mtimeMs,'No identical SSD rewrite');
const sketch=await read('firmware/esp/application.ino'),adapter=await read('firmware/esp/src/AsyncHttpService.h');
assert.match(sketch,/#include "src\/WebUiCompressed.h"/);
assert.match(sketch,/beginResponse\(200,"text\/html; charset=utf-8",kWebUiGzip,sizeof\(kWebUiGzip\)\)/);
assert.match(sketch,/addHeader\("Content-Encoding","gzip"\)/);
assert.match(adapter,/SnapshotResponse\(code,type,reinterpret_cast<const char\*>\(body\),length,pendingOutputObserver\(\)\)/);
console.log('Exact full UI gzip round-trip, portable generation/no rewrites and both-board flash response verified; source/host proof only.');
