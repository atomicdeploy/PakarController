import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const app=read('firmware/esp/application.ino');
const api=read('firmware/esp/src/UsbApiService.h');
const grid=read('firmware/esp/src/LedGrid.cpp');
const select=app.slice(app.indexOf('bool selectLedBackend(const String &name,String &error) {'),app.indexOf('void loadLedPreferences() {'));
assert.match(select,/backendSupported\(selected\)/);
assert.match(select,/otaActive\|\|otaRebootAt\|\|remoteFirmware\.busy\(\)/);
assert.ok(select.indexOf('ledBackendSettings.save(')<select.indexOf('grid.requestBackend('));
assert.match(select,/changes\(\)\.failed\(PakarConfiguration::LedOutput\)/);
assert.match(app,/ledBackendSettings\.begin\(LittleFS,filesystemMounted/);
assert.match(app,/grid\.setInitialBackend\(ledBackendSettings\.selection\(\)\)/);
assert.match(grid,/output_\.begin\(initialBackend_\)/);
const route=app.slice(app.indexOf('server.on("/api/led/output",HTTP_POST'),app.indexOf('server.on("/api/pixels/corrections"'));
assert.match(route,/backend_must_be_requested_separately/);
assert.ok(route.includes('{\\"accepted\\":true,'));
assert.ok(api.includes('{\\"accepted\\":true,'));
assert.match(app,/selectLedBackend\(requested\.backend==1\?"gpio-static":"rmt-dma",error\)/);
assert.match(app,/!PAKAR_S3_LED_GPIO_ENABLED && !PAKAR_S3_LED_RMT_ENABLED/);
assert.match(app,/serviceLedBackendChanges\(\);\s*serviceConfigurationChanges\(\)/);
const pixelCapability='if(BoardCore::Context::pixelEvents(available))body += F(",\\"pixel-events\\"");';
assert.ok(app.includes(pixelCapability),'Both baked roles must advertise the shared LED frame service');
assert.ok(!app.includes('game-presentation\\",\\"pixel-events'),'Pixel events must not depend on the first-wins role');
const subscription=app.slice(app.indexOf('if(parsed["type"]=="pixel-subscribe")'),app.indexOf('if(parsed["type"]=="peer-introduction")'));
assert.match(subscription,/parsed\["enabled"\]\.as<bool>\(\)&&!BoardCore::Context::pixelEvents\(currentFeatures\(\)\)/);
assert.match(subscription,/pixel_events_unavailable/);
assert.ok(subscription.indexOf('pixel_events_unavailable')<subscription.indexOf('PixelObserver *slot'),'Unavailable subscriptions must be rejected before allocating a listener');
assert.match(app,/if\(BoardCore::Context::pixelEvents\(currentFeatures\(\)\)&&!otaActive&&!remoteFirmware\.busy\(\)&&uint32_t\(now-lastPixelObservationAt\)>=33U\)/);
console.log('LED runtime integration: shared ingress, durable intent, truthful receipt, completion event, both-role pixel subscriptions and no-driver capability gates verified (source guards).');
