import assert from 'node:assert/strict';
import {connection,inspect,collect,reviewed,mergeInventory} from '../tools/audit-github-conversations.mjs';
let calls=[];
const rows=connection(after=>{calls.push(after);return after===null?{nodes:[1],pageInfo:{hasNextPage:true,endCursor:'next'}}:{nodes:[2],pageInfo:{hasNextPage:false,endCursor:null}}});
assert.deepEqual(rows,[1,2]);assert.deepEqual(calls,[null,'next']);
assert.throws(()=>connection(()=>({nodes:[],pageInfo:{hasNextPage:true,endCursor:null}})),/cursor/);
assert.throws(()=>connection(()=>({nodes:[],pageInfo:{hasNextPage:true,endCursor:'repeat'}})),/cursor/);
assert.throws(()=>connection(()=>({nodes:[]})),/Incomplete/);
assert.throws(()=>collect('../bad'),/Invalid/);
const record={repository:'owner/repo',number:1,kind:'pull_request',title:'Test',url:'https://github.com/owner/repo/pull/1',state:'closed',body:'Copilot requested',comments:[],reviews:[],threads:[{id:'pending',isResolved:false,comments:[]},{id:'done',isResolved:true,comments:[]}]};
const checked=inspect(record);
assert.equal(checked.read_state,'pending');assert.deepEqual(checked.unresolved_threads,['pending']);
assert.equal(checked.content_sha256,inspect(record).content_sha256);
assert.notEqual(checked.content_sha256,inspect({...record,body:'Changed'}).content_sha256);
assert.equal(checked.copilot_messages,0,'Human mentions are not completed Copilot reviews');
const notice=inspect({...record,reviews:[{body:'Review quota exhausted',author:{login:'copilot-pull-request-reviewer'}}]});
assert.equal(notice.copilot_messages,1);assert.equal(notice.copilot_quota_notices,1);
const decision={repository:record.repository,number:1,content_sha256:checked.content_sha256,scope:'full-record',application:'Read, not resolved; keep the open finding pending.'};
assert.equal(reviewed([checked],[decision])[0].read_state,'reviewed-record');
assert.deepEqual(reviewed([checked],[decision])[0].unresolved_threads,['pending']);
assert.equal(reviewed([inspect({...record,body:'Changed'})],[decision])[0].read_state,'stale-review');
const retained={...checked,repository:'other/donor',read_state:'reviewed-record'};
const changed=inspect({...record,body:'Changed'});
const added={...checked,number:2};
assert.deepEqual(mergeInventory([checked,retained],[changed,added]),[changed,retained,added],
  'Targeted audit without a raw cache must preserve other donor records and their exact evidence');
assert.deepEqual(mergeInventory([retained],[]),[retained]);
assert.deepEqual(mergeInventory([], [checked]),[checked]);
assert.deepEqual(mergeInventory([checked,retained],[checked,retained]),[checked,retained]);
console.log('Paginated GitHub audit: completeness, stable hashes, no review promotion and cold-cache inventory preservation passed.');
