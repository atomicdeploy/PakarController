// Reuse the same immutable artwork, palette and peer-bound HTTP transport.
// No package manager, second client protocol or externally hosted assets.
import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import {webPeerSource} from './web-peer-build.mjs';
const read = path => readFile(new URL('../'+path, import.meta.url), 'utf8');
const icon=(await read('assets/branding/app-icon.png.base64')).trim();
assert.match(icon,/^[A-Za-z0-9+/]+={0,2}$/);
const palette=JSON.parse(await read('assets/themes/palettes.json')).studio.dark;
const values={
  APP_ICON:'data:image/png;base64,'+icon,
  PALETTE:':root{color-scheme:dark;'+Object.entries(palette).map(([key,value])=>'--'+key+':'+value).join(';')+'}',
  PEER_HTTP:await webPeerSource(await read('assets/web/peer-http.js')),
  BASIC_CELLS:await read('assets/web/basic-cells.js'),
};
let html=await read('assets/web/basic.html');
for(const [name,value]of Object.entries(values)){
  assert(!value.includes(')BASIC"'),'Raw-string terminator in '+name);
  if(name==='PEER_HTTP'||name==='BASIC_CELLS')assert(!/<\/script/i.test(value),'Script terminator in '+name);
  assert(html.includes('{{'+name+'}}'),'Missing '+name+' marker');
  html=html.replaceAll('{{'+name+'}}',()=>value.replace(/\r\n/g,'\n'));
}
assert(!/\{\{[A-Z_]+\}\}/.test(html),'Unresolved basic UI template');
const header='// Generated by tools/generate-basic-ui.mjs; edit assets/web/basic* instead.\n#pragma once\n#include <Arduino.h>\nstatic const char kBasicUi[] PROGMEM = R"BASIC('+html+')BASIC";\n';
const output=new URL('../firmware/esp8266/src/BasicUi.h',import.meta.url);
let previous;try{previous=await readFile(output,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
if(previous!==header){
  assert(!process.argv.includes('--check'),'Basic cell UI is stale; run node tools/generate-basic-ui.mjs');
  await writeFile(output,header);
}
console.log('Basic cell app assets current: '+Buffer.byteLength(html)+' bytes; shared HTTP/artwork/palette.');
