// Preserve the canonical UI exactly; only its immutable ESP8266 wire/storage
// representation changes. Reuse the font pipeline's portable, timestamp-free gzip.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {portableGzip} from './portable-gzip.mjs';
export function webUiPayload(source){
  const normalized=source.replaceAll('\r\n','\n');
  const match=/R"HTML\(([\s\S]*)\)HTML";/.exec(normalized);
  assert(match,'Expected the single canonical Web UI raw literal');
  assert.equal(normalized.split('R"HTML(').length,2,'One UI source');
  return Buffer.from(match[1],'utf8');
}
export function compressedWebHeader(source){
  const raw=webUiPayload(source),gzip=portableGzip(raw),lines=[];
  assert(gzip.length<raw.length,'Compression must save flash');
  for(let at=0;at<gzip.length;at+=24)lines.push('  '+[...gzip.subarray(at,at+24)].join(',')+',');
  return {raw,gzip,header:'// Generated by tools/generate-web-compressed.mjs from the full canonical WebUi.h.\n'+
    '// ESP8266 only: same HTML/CSS/JavaScript; HTTP Content-Encoding: gzip.\n#pragma once\n#include <Arduino.h>\n'+
    'static const uint8_t kWebUiGzip[] PROGMEM = {\n'+lines.join('\n')+'\n};\n'};
}
export async function generateWebCompressed({check=false}={}){
  const root=new URL('../',import.meta.url),output=new URL('firmware/esp/src/WebUiCompressed.h',root);
  const value=compressedWebHeader(await readFile(new URL('firmware/esp/src/WebUi.h',root),'utf8'));
  let previous;try{previous=await readFile(output,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
  if(previous!==value.header){assert(!check,'Compressed Web UI stale; run node tools/generate-web-compressed.mjs');await writeFile(output,value.header);}
  return {raw:value.raw.length,gzip:value.gzip.length};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const result=await generateWebCompressed({check:process.argv.includes('--check')});
  console.log('Full ESP8266 Web UI: '+result.raw+' bytes -> '+result.gzip+' portable gzip bytes; no feature removal.');
}
