// Editable SVG masters; optional external sharp rasterizer only at generation.
// Check mode needs no image dependency. Transport PNGs respect existing 4096B bounds.
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url), check=process.argv.includes('--check');
async function put(path,value){const url=new URL(path,root);let old;try{old=await readFile(url)}catch{}const data=Buffer.from(value);if(old?.equals(data))return;assert(!check,`Stale board artwork: ${path}`);await writeFile(url,data);}
const icons={};
for(const role of ['table','keys']){
 const path=`assets/branding/${role}.png.base64`;
 if(!check){const require=createRequire(import.meta.url);const sharp=require(process.env.PAKAR_SHARP_MODULE||'sharp');
  const svg=await readFile(new URL(`assets/branding/${role}.svg`,root));
  for(const size of [24,256]) await put(`assets/branding/${role}-${size}.png`,await sharp(svg).resize(size,size).png().toBuffer());
  const png=await sharp(svg).resize(64,64).png({palette:true,colours:64}).toBuffer();
  await put(path,png.toString('base64')+'\n');
 }
 icons[role]=(await readFile(new URL(path,root),'utf8')).trim();
 assert(icons[role].length<=4096,'Board artwork exceeds peer transport limit');
}
await put('firmware/esp/src/BoardArtwork.h','#pragma once\n#include <Arduino.h>\n'+Object.entries(icons).map(([k,v])=>`static const char kBoardIcon_${k}[] PROGMEM = "${v}";`).join('\n')+'\n');
await put('mobile/lib/board_artwork.dart','// Generated by generate-board-artwork.mjs\nimport "dart:convert";\nimport "dart:typed_data";\nfinal Map<String, Uint8List> boardArtwork = {\n'+Object.entries(icons).map(([k,v])=>`  '${k==='table'?'table-selection':'first-wins'}': base64Decode('${v}'),`).join('\n')+'\n};\n');
console.log('Board artwork generated/checked within peer bounds.');
